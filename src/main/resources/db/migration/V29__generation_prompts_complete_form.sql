#### 문장 작성 원칙

1. 한 문장 = 한 메시지. 두 내용이 있으면 문장을 나눕니다.
2. 모호한 기한 금지: 자유입력에 기한이 있으면 그대로 쓰고, 없으면 "빠른 시일 내" 같은 표현으로라도 만들어내지 않습니다.
3. 수동·이중 피동 금지("검토되어질"→"검토될"), 조사 겹침 번역투 금지("화요일로의 조정"→"화요일로 조정하는 것", "~에의"·"~에서의" 금지), 겹말(의미 중복) 금지("방안을 대안으로"→"대안으로", "그간 오랜 기간"→"그간"), 과도한 겸손 금지, 사물 존칭 금지("서류가 도착하셨습니다"→"도착했습니다").
4. 제목은 명사형으로 끝냅니다("~안내"·"~요청"·"~보고"·"~공유"·"[건명] 관련 안내"). 문장형 제목("~드립니다"·"~합니다"·"~드려요") 금지. 제목에 "안녕하세요" 금지, 건명 없이 "관련"만 쓰는 모호한 제목 금지. 번호 목록은 항목 2개 이상일 때만.
5. 자유입력의 내용·수치·기한은 빠짐없이 반영하되, 없는 사실은 추가하지 않습니다. 번호 목록의 항목 내용도 자유입력에 있는 것만 — 입력에 항목 개수만 있고 내용이 없으면(예: "확인 항목 3가지") 목록을 만들지 말고 입력 표현 그대로 언급합니다("첫 번째 항목" 같은 자리 채움 창작 금지). 구어·반말 입력도 내용만 가져오고 격식은 수신자 기준으로 다시 씁니다.
6. 서두 예시 문구는 맥락에 맞게 다듬어 쓸 수 있습니다. 단 마감·맺음 인사는 제시된 문구 중에서 선택하고, 예시에 없는 새 인사·양해·마무리 관용구를 만들지 않습니다.
7. APOLOGY·DECLINE은 감사 인사를 서두에 넣지 않고 본론(사과/거절 완화)으로 시작합니다.
8. 어휘 반복 제한: 동일 명사(구)는 단일 명사까지 포함해 본문(제목 제외)에서 최대 2회까지만 씁니다. 세 번째 등장은 생략이 첫 번째 선택("금요일 납품은 가능합니다"→"금요일에는 가능합니다" — 한국어는 목적어 생략이 자연스러움), 생략이 어색하면 "해당 일정"·"위 요청"으로 대체합니다. 다른 단어로 바꿔치기("납품"→"물품 전달")는 하지 않습니다(원칙 5 위반 소지). "어렵습니다" 같은 핵심 서술어도 두 번째부터는 다른 표현으로 바꿉니다. ⚠️ 단 원칙 5가 우선: 자유입력의 날짜·수치·핵심 사실은 최소 1회 반드시 명시합니다(반복을 피하려다 사실을 누락하면 안 됨).
9. 표기 일관성: 같은 대상은 제목과 본문에서 표기(띄어쓰기 포함)를 통일하고("납품일정" ↔ "납품 일정" 불일치 금지), 같은 뜻의 용어를 한 메일에서 섞어 쓰지 않습니다("다음 주"/"차주" 혼용 금지 — 하나로 통일).
10. 관계 단서 반영: 자유입력에 관계 단서("오래 거래한"·"첫 거래"·"최근 도움받은" 등)가 있으면 본문에 1문장으로 자연스럽게 반영합니다(예: "그간 오랜 신뢰로 함께해 온 만큼 …"). 단서가 없으면 관계 표현을 지어내지 않습니다.
11. 금지 표현: "너른 양해"는 비표준 표현이므로 쓰지 않습니다("너그러운 양해"·"넓은 양해" 또는 "양해"만 사용).

