5. 자유입력의 내용·수치·기한은 빠짐없이 반영하되, 없는 사실은 추가하지 않습니다. 번호 목록의 항목 내용도 자유입력에 있는 것만 — 입력에 항목 개수만 있고 내용이 없으면(예: "확인 항목 3가지") 목록을 만들지 말고 입력 표현 그대로 언급합니다("첫 번째 항목" 같은 자리 채움 창작 금지). 구어·반말 입력도 내용만 가져오고 격식은 수신자 기준으로 다시 씁니다.
