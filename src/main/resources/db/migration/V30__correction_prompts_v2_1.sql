- RCP-04 기본 어체(해요체(기본)) 정상 표현
- 공문체 관례: "자료를 제출합니다" 등

[2단계 — 확정 오류(필수). 1단계 보호 안 걸린 것만]
- 무관 사물 주어 + '-시-' → '-시-' 제거 (예: "서류가 도착하셨습니다" → "도착했습니다")
- 사물·사건 주어 + "계시다" → "있다/있으시다"
- "되요/됬" → "돼요/됐"
- "~ㄹ께요" → "~ㄹ게요"
- 이중 피동 "되어지다" → "되다" (예: "검토되어집니다" → "검토됩니다")
- 명사 + 공백 + 드리다 → 붙여쓰기 (예: "부탁 드립니다" → "부탁드립니다")
- '-시-' + '-ㄹ게요' 결합("하실게요") → '-시-' 제거(선언은 '-시겠습니다', 요청은 '-시겠어요?')
- 어체 위반: 격식 관계에서 해요체 종결('보내드려요') → 하십시오체('보내드립니다')
- 빈출 맞춤법: 몇일→며칠, 금새→금세, 않되다→안 되다, ~시요→~세요 등 명백한 표기 오류
- 물결(~)·이모티콘(^^, ㅠㅠ)·자음 감탄(ㅋㅋ, ㅎㅎ)은 해요체 관계에서 자연스러우므로 교정하지 않습니다(보호).

[3단계 — 제안·권고(권장/선택). 1·2단계 안 걸린 것만, 트리거 범위 엄격]
- [선택·반복] "부탁드립니다/부탁드려요"가 문서 전체에서 3회 이상 반복되면 반드시 선택 1건을 발동합니다: 3개 중 하나만 골라 다른 표현("말씀해 주시면 감사하겠습니다" / "부탁드려도 될까요" 등)으로 변형 제안. 문서 전체의 등장 횟수를 세어 판정하고, 2회 이하이면 발동하지 않습니다. (개별 "부탁드립니다"는 정상 표현이라 반복이 아니면 손대지 않음.)
