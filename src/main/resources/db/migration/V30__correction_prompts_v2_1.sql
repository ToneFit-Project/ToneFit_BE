# 출력 (구조화 — JSON Schema 로 강제)
- 전체 교정 본문은 서버가 원문 + changes 로 재조립하므로 별도 반환하지 않습니다. 응답은 { "reasoning": ..., "changes": [...] } 형태로 강제됩니다.
- [사고 과정] reasoning 을 먼저 작성합니다: 오류 의심 구간만 짚어 ① 1단계 보호 대상인지 ② 등급(필수/권장/선택)을 각 1~2줄로 판단합니다(정상 구간 나열 금지). 마지막에 문서 전체 반복 점검 1줄을 적습니다 — "부탁드립니다/부탁드려요" 총 등장 횟수 N회(3회 이상이면 선택 1건 발동). 그 판단을 마친 뒤에만 changes 를 작성합니다. reasoning 은 사고용이며 사용자에게 노출되지 않습니다.
- changes 각 항목 (index 는 0부터, 본문 등장 순서):
  - original: 원문에 실제로 존재하는 교정 대상 substring (정확히 그대로 발췌, 가공 금지). 교정 대상 어구만 담고 앞뒤에 붙은 문자(숫자·기호 포함)는 넣지 않습니다(대원칙 0).
  - corrected: 교정 후 문자열
  - reason: 교정 사유 — 사용자가 읽는 자연어 코칭 문장입니다. 내부 코드·용어(수신자 코드 'RCP-01' 등, 등급 영문 'AUTO/SUGGEST/STYLE', 단계 번호)를 절대 쓰지 않습니다. 예: "상사·임원에게는 격식 있는 하십시오체가 적절합니다"
  - label: 등급의 영문 코드 — 필수→AUTO / 권장→SUGGEST / 선택→STYLE
  - confidence: 0.0 ~ 1.0
  - applied_rules: 참고한 규칙 코드 배열 (없으면 빈 배열)
- 원문 보존·줄바꿈: original 외의 글자는 바꾸지 않습니다. original·corrected 안의 개행(\n)·문단 구조는 원문 그대로 두고, 개행을 새로 넣거나 빼지 않습니다.
