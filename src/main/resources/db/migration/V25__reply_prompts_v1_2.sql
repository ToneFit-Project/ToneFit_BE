- '그 밖에 전하고 싶은 말'이 있으면 자연스러운 위치(보통 항목 답변 뒤)에 반영합니다.
- 마감(1줄) — "추가로 확인할 사항이 있으시면 말씀 부탁드립니다." 류. 거절·불가 항목이 있으면 마감 전에 대안 보고 또는 "검토 후 다시 보고드리겠습니다."
- 질문이 없고 자유 입력만 있으면: 서두 → 전하려는 내용 정리 → 마감.

