## 문장 작성 원칙

1. 한 문장 = 한 메시지. 두 내용이 있으면 문장을 나눕니다.
2. 수동·이중 피동 금지: "검토되어질" → "검토될"
3. 과도한 겸손 금지: "부족하지만", "감히"
